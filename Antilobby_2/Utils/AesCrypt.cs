  /// <summary>
  /// Initializes a new instance of the <see cref="AesCrypt"/> class.
  /// A unique key and IV will be generated internally by the AesCryptoServiceProvider
  /// when encryption or decryption methods are called if not set externally.
  /// </summary>
  public AesCrypt() {
        // Key and IV are typically generated by the AesCryptoServiceProvider instance.
        // If you need to use a specific key or IV, they should be set before calling encrypt/decrypt.
        // For simplicity, this constructor does not explicitly initialize them, relying on the
        // 'using (AesCryptoServiceProvider myAes = new AesCryptoServiceProvider())' block
        // in encrypt/decrypt methods to generate them per operation if this.key/this.IV are not pre-set.
        // However, for consistent decryption, the SAME key and IV must be used.
        // This class structure implies that encrypt and then decrypt operations on the same instance
        // might not work as expected if key/IV are not managed carefully (e.g. set from outside or persisted).
        // The current encrypt/decrypt methods generate a new key/IV each time they are called
        // because a new AesCryptoServiceProvider is instantiated. This is not typical for session-based encryption.
        // For the purpose of this documentation, we assume the key and IV might be set externally or this behavior is intended.
        using (AesCryptoServiceProvider myAes = new AesCryptoServiceProvider()) {
            this.key = myAes.Key; // Store a generated key for potential later use (though encrypt/decrypt override)
            this.IV = myAes.IV;   // Store a generated IV for potential later use
        }
  }


  /// <summary>
  /// Decrypts the given byte array using AES.
  /// Note: This method uses the instance's 'key' and 'IV' fields. Ensure these are set to the
  /// same values used during encryption for successful decryption.
  /// </summary>
  /// <param name="encrypted">The byte array containing the encrypted data.</param>
  /// <returns>The decrypted string. Returns null if decryption fails or input is invalid.</returns>
  public string decrypt(byte[] encrypted) {
    //This method as implemented will use a new Key and IV each time, unless this.key and this.IV are PRE-SET from outside.
    //To decrypt successfully, the Key and IV must match those used for encryption.
    if (this.key == null || this.IV == null) {
        // Consider throwing an exception or logging an error if key/IV are not set,
        // as decryption will likely fail or use unintended default values.
        // For now, we proceed, but this is a potential issue.
