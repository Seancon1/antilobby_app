            this.key = tempAes.Key; // Fallback, but likely not the correct key for decryption
            this.IV = tempAes.IV;   // Fallback, but likely not the correct IV
        }
    }
    using (AesCryptoServiceProvider myAes = new AesCryptoServiceProvider()) {
      myAes.Key = this.key;
      myAes.IV = this.IV;
      // Decrypt the bytes to a string.
      string roundtrip =
          DecryptStringFromBytes_Aes(encrypted, myAes.Key, myAes.IV);

      // Display the original data and the decrypted data.
      // Console.WriteLine("Original:   {0}", original);
      // Console.WriteLine("Round Trip: {0}", roundtrip);

      return roundtrip;
    }
  }

  /// <summary>
  /// Encrypts the given string using AES.
  /// A new key and IV are generated for this encryption operation by default.
  /// The generated IV is stored in the instance's 'IV' property. The key is stored internally.
  /// </summary>
  /// <param name="original">The string to encrypt.</param>
  /// <returns>A byte array containing the encrypted data.</returns>
  public byte[] encrypt(string original) {
    using (AesCryptoServiceProvider myAes = new AesCryptoServiceProvider()) {
      this.key = myAes.Key; // Store the key used for this encryption
      this.IV = myAes.IV;   // Store the IV used for this encryption
      // Encrypt the string to an array of bytes.
      byte[] encrypted =
          EncryptStringToBytes_Aes(original, myAes.Key, myAes.IV);
      return encrypted;
    }
  }

  // Core AES encryption logic. Converts a plaintext string to an encrypted byte array using the provided Key and IV.
  static byte[] EncryptStringToBytes_Aes(string plainText, byte[] Key,
                                         byte[] IV) {
    // Check arguments.
    if (plainText == null || plainText.Length <= 0)
      throw new ArgumentNullException("plainText");
    if (Key == null || Key.Length <= 0)
      throw new ArgumentNullException("Key");
    if (IV == null || IV.Length <= 0)
      throw new ArgumentNullException("IV");
    byte[] encrypted;

    // Create an AesCryptoServiceProvider object
    // with the specified key and IV.
    using (AesCryptoServiceProvider aesAlg = new AesCryptoServiceProvider()) {
      aesAlg.Key = Key;
      aesAlg.IV = IV;

      // Create an encryptor to perform the stream transform.
      ICryptoTransform encryptor =
          aesAlg.CreateEncryptor(aesAlg.Key, aesAlg.IV);

      // Create the streams used for encryption.
      using (MemoryStream msEncrypt = new MemoryStream()) {
        using (CryptoStream csEncrypt = new CryptoStream(
                   msEncrypt, encryptor, CryptoStreamMode.Write)) {
          using (StreamWriter swEncrypt = new StreamWriter(csEncrypt)) {
            // Write all data to the stream.
            swEncrypt.Write(plainText);
          }
          encrypted = msEncrypt.ToArray();
        }
      }
    }

    // Return the encrypted bytes from the memory stream.
    return encrypted;
  }

  // Core AES decryption logic. Converts an encrypted byte array back to a plaintext string using the provided Key and IV.
  static string DecryptStringFromBytes_Aes(byte[] cipherText, byte[] Key,
                                           byte[] IV) {
    // Check arguments.
    if (cipherText == null || cipherText.Length <= 0)
      throw new ArgumentNullException("cipherText");
    if (Key == null || Key.Length <= 0)
      throw new ArgumentNullException("Key");
    if (IV == null || IV.Length <= 0)
      throw new ArgumentNullException("IV");

    // Declare the string used to hold
    // the decrypted text.
    string plaintext = null;

    // Create an AesCryptoServiceProvider object
    // with the specified key and IV.
    using (AesCryptoServiceProvider aesAlg = new AesCryptoServiceProvider()) {
      aesAlg.Key = Key;
      aesAlg.IV = IV;

      // Create a decryptor to perform the stream transform.
      ICryptoTransform decryptor =
          aesAlg.CreateDecryptor(aesAlg.Key, aesAlg.IV);

      // Create the streams used for decryption.
      using (MemoryStream msDecrypt = new MemoryStream(cipherText)) {
        using (CryptoStream csDecrypt = new CryptoStream(
                   msDecrypt, decryptor, CryptoStreamMode.Read)) {
          using (StreamReader srDecrypt = new StreamReader(csDecrypt)) {

            // Read the decrypted bytes from the decrypting stream
            // and place them in a string.
            plaintext = srDecrypt.ReadToEnd();
          }
        }
      }
    }

    return plaintext;
  }
}
